test('baseline: with or without graphify the run enables core.hooksPath', () => {
  const sb = sandbox({ tools: ['git', 'bun'], git: true });
  expect(fs.existsSync(path.join(sb.repo, '.git'))).toBe(true);
  const gitEnv = { ...sb.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' };
  const git = (...args) => Bun.spawnSync([path.join(sb.bin, 'git'), '-C', sb.repo, 'config', ...args], { env: gitEnv });
  // Negative control: before the run the same read reports no value, so a pass below comes from the run.
  expect(git('--get', 'core.hooksPath').exitCode).toBe(1);
  const r = sb.run([]);
  expect(r.status).toBe(0);
  // The run took the missing-graphify branch and still set the hooks path.
  expect(r.stderr).toContain("optional tool 'graphify' not found");
  expect(r.stderr).not.toContain('skipping core.hooksPath');
  const after = git('--get', 'core.hooksPath');
  expect(after.exitCode).toBe(0);
  expect(after.stdout.toString().trim()).toBe('.githooks');
});

test('baseline: the layout check fails when the installer targets another path', () => {
  // Mutation proof that the comparison above can fail: change one target in the sandbox copy only.
  const sb = sandbox({ tools: ['git', 'bun'] });
  // The link targets live in targets.sh; install.sh only mentions the path in its usage text.
  const script = path.join(sb.repo, 'scripts/install/targets.sh');
  const src = fs.readFileSync(script, 'utf8');
  expect(src).toContain('.agents/skills');
  fs.writeFileSync(script, src.replaceAll('.agents/skills', '.agentz/skills'));
  expect(sb.run([]).status).toBe(0);
  expect(() => expectLayout(sb)).toThrow();
});

test('sandbox: assertSandbox accepts the sandbox env and rejects any HOME outside it', () => {
  const sb = sandbox();
  expect(() => assertSandbox(sb.env)).not.toThrow();
  expect(() => assertSandbox({ ...sb.env, HOME: os.homedir() })).toThrow(/sandbox/i);
  expect(() => assertSandbox({ ...sb.env, HOME: '/var/empty' })).toThrow(/sandbox/i);
  expect(() => assertSandbox({ ...sb.env, HOME: os.tmpdir() })).toThrow(/sandbox/i);
  expect(() => assertSandbox({ PATH: sb.bin })).toThrow(/sandbox/i);
  // A link inside the temp dir that points outside it must not pass.
  const escape = path.join(sb.root, 'escape');
  fs.symlinkSync('/usr', escape);
  expect(() => assertSandbox({ ...sb.env, HOME: escape })).toThrow(/sandbox/i);
});

test('sandbox: run refuses a HOME override that leaves the sandbox before spawning anything', () => {
  const sb = sandbox();
  // -h exits before the installer does anything, so even a broken guard could not write here.
  expect(() => sb.run(['-h'], { env: { HOME: os.homedir() } })).toThrow(/sandbox/i);
});

test('sandbox: PATH holds only the base tools plus the named ones, and env holds nothing else', () => {
  const none = sandbox({ tools: [] });
  expect(fs.existsSync(path.join(none.bin, 'bash'))).toBe(true);
  expect(fs.existsSync(path.join(none.bin, 'bun'))).toBe(false);
  expect(fs.existsSync(path.join(none.bin, 'git'))).toBe(false);
  const both = sandbox({ tools: ['git', 'bun'] });
  expect(fs.realpathSync(path.join(both.bin, 'git'))).toBe(fs.realpathSync(Bun.which('git')));
  expect(fs.realpathSync(path.join(both.bin, 'bun'))).toBe(fs.realpathSync(Bun.which('bun')));
  expect(both.env).toEqual({
    HOME: both.home,
    PATH: both.bin,
    VIVERA_NOW: '20260101T000000Z',
    TMPDIR: path.join(both.root, 'tmp'),
    LANG: 'C',
    BUN_RUNTIME_TRANSPILER_CACHE_PATH: '0',
  });
  expect(sandbox({ extraEnv: { FOO: '1' } }).env.FOO).toBe('1');
  expect(() => makeSandbox({ tools: ['no-such-tool-vivera-xyz'] })).toThrow(/no-such-tool-vivera-xyz/);
});

test('sandbox: the repo is a payload copy that keeps symlinks, has no .git and links node_modules', () => {
  const sb = sandbox();
  for (const rel of INSTALL_PAYLOAD) {
    const src = path.join(WORKTREE, rel);
    if (fs.existsSync(src)) expect(fs.existsSync(path.join(sb.repo, rel))).toBe(true);
  }
  expect(fs.existsSync(path.join(sb.repo, '.git'))).toBe(false);
  expect(fs.readlinkSync(path.join(sb.repo, 'node_modules'))).toBe(path.join(WORKTREE, 'node_modules'));
  const link = 'skills/super-ultra-code-plan/SKILL.md';
  expect(fs.readlinkSync(path.join(sb.repo, link))).toBe(fs.readlinkSync(path.join(WORKTREE, link)));
});

test('sandbox: snapshot lists files by hash and links by target without following them', () => {
  const sb = sandbox();
  fs.mkdirSync(path.join(sb.home, 'd'));
  fs.writeFileSync(path.join(sb.home, 'd/f'), 'a');
  fs.symlinkSync(sb.repo, path.join(sb.home, 'lnk'));
  const sha = createHash('sha256').update('a').digest('hex');
  expect(sb.snapshot()).toEqual([`d/f|f|${sha}`, 'd|d|', `lnk|l|${REPO_REF}`].sort());
  fs.writeFileSync(path.join(sb.home, 'd/f'), 'b');
  expect(sb.snapshot()).not.toContain(`d/f|f|${sha}`);
});
