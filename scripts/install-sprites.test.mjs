// scripts/install-sprites.test.mjs
//
// The Harvest Sprite crew rendered into six harnesses by install, update, check and uninstall:
// Claude Code, OpenCode, Codex, Cursor, Copilot and Antigravity. bun is the real one here, and the
// sandbox repo copy has node_modules linked, so the generator really runs; every run uses the sandbox
// from scripts/lib/install-sandbox.mjs, so no real harness config is written.

import { afterEach, describe, expect, test } from 'bun:test';
import fs from 'node:fs';
import path from 'node:path';
import { makeSandbox } from './lib/install-sandbox.mjs';

const MARKER = '# Generated by scripts/gen-sprite-agents.mjs';
const MASTER = 'Super Ultra Code Plan Implementation.md';

// id -> where the sprites go and how each sprite file is named.
const HARNESS = {
  claude: { dir: '.claude/agents', file: (s) => `${s}.md`, note: (sb) => `hook root ${sb.repo}` },
  opencode: { dir: '.config/opencode/agents', file: (s) => `${s}.md`, note: () => 'OpenCode format' },
  codex: { dir: '.codex/agents', file: (s) => `${s}.toml`, note: () => 'Codex format' },
  cursor: { dir: '.cursor/agents', file: (s) => `${s}.md`, note: () => 'Cursor format' },
  copilot: { dir: '.copilot/agents', file: (s) => `${s}.agent.md`, note: () => 'Copilot format' },
  antigravity: { dir: '.gemini/config/agents', file: (s) => `${s}/agent.md`, note: () => 'Antigravity format' },
};
const IDS = Object.keys(HARNESS);
const HARNESS_ROOTS = ['.claude', '.config/opencode', '.gemini', '.codex', '.cursor', '.copilot'];

const open = [];
afterEach(() => {
  while (open.length) open.pop().cleanup();
});

function sandbox({ tools = ['git', 'bun'] } = {}) {
  const sb = makeSandbox({ tools });
  open.push(sb);
  return sb;
}

const at = (sb, rel) => path.join(sb.home, rel);
const exists = (sb, rel) => fs.existsSync(at(sb, rel));
const mkdir = (sb, rel) => fs.mkdirSync(at(sb, rel), { recursive: true });
const sprites = (sb) => JSON.parse(fs.readFileSync(path.join(sb.repo, 'agents/crew.json'), 'utf8')).map((c) => c.sprite);
const fullHome = (sb) => HARNESS_ROOTS.forEach((d) => mkdir(sb, d));
const spriteFiles = (sb, id) => sprites(sb).map((s) => at(sb, `${HARNESS[id].dir}/${HARNESS[id].file(s)}`));
const isGenerated = (file) => fs.readFileSync(file, 'utf8').split('\n').some((l) => l.startsWith(MARKER));
const backupsUnder = (sb) => sb.snapshot(sb.root).filter((l) => l.split('|')[0].includes('.vivera-bak-'));

describe('install', () => {
  test('sprites: a home with every harness gets seven generated files of the right shape in each', () => {
    const sb = sandbox();
    fullHome(sb);
    const r = sb.run([]);
    expect(r.status).toBe(0);
    expect(sprites(sb).length).toBe(7);
    for (const id of IDS) {
      for (const file of spriteFiles(sb, id)) {
        expect({ id, file, exists: fs.existsSync(file) }).toEqual({ id, file, exists: true });
        expect({ id, file, generated: isGenerated(file) }).toEqual({ id, file, generated: true });
      }
    }
    // Only Claude Code runs a hook, so only its files name this checkout as the hook root.
    for (const file of spriteFiles(sb, 'claude')) expect(fs.readFileSync(file, 'utf8')).toContain(sb.repo);

    const first = sb.snapshot();
    expect(sb.run([]).status).toBe(0);
    expect(sb.snapshot()).toEqual(first);
  });

  test('sprites: --only codex on a bare HOME renders just the Codex files, and says its skills come from ~/.agents/skills', () => {
    const sb = sandbox();
    const r = sb.run(['--only', 'codex']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain('[INFO] codex: no skills target of its own (its skills come from ~/.agents/skills); installing its sprite agents only');
    for (const file of spriteFiles(sb, 'codex')) expect(isGenerated(file)).toBe(true);
    expect(fs.readdirSync(sb.home)).toEqual(['.codex']);
    expect(fs.readdirSync(at(sb, '.codex'))).toEqual(['agents']);
  });

  test('sprites: --tier minimal renders none and never calls bun, even with no bun on PATH', () => {
    const sb = sandbox({ tools: [] });
    fullHome(sb);
    const r = sb.run(['--tier', 'minimal']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain('[SKIP] sprite agents: tier minimal needs no bun');
    for (const id of IDS) expect(exists(sb, HARNESS[id].dir)).toBe(false);
  });

  test('sprites: --dry-run writes nothing and says what it would render for all six harnesses', () => {
    const sb = sandbox();
    fullHome(sb);
    const before = sb.snapshot();
    const r = sb.run(['--dry-run']);
    expect(r.status).toBe(0);
    for (const id of IDS) {
      expect(r.stdout).toContain(`[DRY-RUN] Would render the sprite agents into: ${at(sb, HARNESS[id].dir)} (${HARNESS[id].note(sb)})`);
    }
    expect(sb.snapshot()).toEqual(before);
  });
});

describe('check', () => {
  function installed() {
    const sb = sandbox();
    fullHome(sb);
    expect(sb.run([]).status).toBe(0);
    return sb;
  }

  test('sprites: after an install check is CURRENT with an [ok] line per sprite dir', () => {
    const sb = installed();
    const r = sb.run(['--check']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain('check: CURRENT');
    for (const id of IDS) expect(r.stdout).toContain(`[ok] ${at(sb, HARNESS[id].dir)} (sprite agents)`);
  });

  test('sprites: --check --only codex counts the Codex sprite dir, so it is neither nothing-to-check nor a problem once rendered', () => {
    const sb = sandbox();
    expect(sb.run(['--only', 'codex']).status).toBe(0);
    const r = sb.run(['--check', '--only', 'codex']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain('[skip] codex: no skills target');
    expect(r.stdout).toContain(`[ok] ${at(sb, '.codex/agents')} (sprite agents)`);
    expect(r.stdout).toContain('check: CURRENT');
  });

  test('sprites: an edited generated file is [stale], a removed sprite dir is [missing], each exit 1', () => {
    const sb = installed();
    const [codexFile] = spriteFiles(sb, 'codex');
    fs.appendFileSync(codexFile, '\n# edited by hand\n');
    const stale = sb.run(['--check']);
    expect(stale.status).toBe(1);
    expect(stale.stdout).toContain(
      `[stale] ${at(sb, '.codex/agents')} (sprite agents are out of date or hand-edited; --update renders them again)`,
    );
    expect(stale.stdout).toContain('check: 1 problem(s)');

    fs.rmSync(at(sb, '.cursor/agents'), { recursive: true });
    const missing = sb.run(['--check']);
    expect(missing.status).toBe(1);
    expect(missing.stdout).toContain(`[missing] ${at(sb, '.cursor/agents')} (sprite agents)`);
    expect(missing.stdout).toContain('check: 2 problem(s)');
  });

  test('sprites: without bun on PATH check skips the sprite dirs and the exit status comes from the skills alone', () => {
    const sb = installed();
    fs.rmSync(path.join(sb.bin, 'bun'));
    const r = sb.run(['--check']);
    expect(r.status).toBe(0);
    for (const id of IDS) expect(r.stdout).toContain(`[skip] ${id} sprites: bun not found`);
    expect(r.stdout).toContain('check: CURRENT');
  });
});

describe('update and uninstall', () => {
  test('sprites: update renders a tampered file again and leaves an unmarked hand-written one beside them', () => {
    const sb = sandbox();
    fullHome(sb);
    expect(sb.run([]).status).toBe(0);
    const [file] = spriteFiles(sb, 'cursor');
    const original = fs.readFileSync(file, 'utf8');
    fs.appendFileSync(file, '\ntampered\n');
    const mine = at(sb, '.cursor/agents/mine.md');
    fs.writeFileSync(mine, 'my own agent\n');
    const r = sb.run(['--update']);
    expect(r.status).toBe(0);
    expect(fs.readFileSync(file, 'utf8')).toBe(original);
    expect(fs.readFileSync(mine, 'utf8')).toBe('my own agent\n');
  });

  test('sprites: uninstall removes the generated files and the dirs it emptied, keeps an unmarked file and its dir', () => {
    const sb = sandbox();
    fullHome(sb);
    expect(sb.run([]).status).toBe(0);
    const mine = at(sb, '.codex/agents/mine.toml');
    fs.writeFileSync(mine, 'name = "mine"\n');
    const r = sb.run(['--uninstall']);
    expect(r.status).toBe(0);
    for (const id of IDS) for (const file of spriteFiles(sb, id)) expect(fs.existsSync(file)).toBe(false);
    for (const id of IDS.filter((i) => i !== 'codex')) expect(exists(sb, HARNESS[id].dir)).toBe(false);
    expect(fs.readFileSync(mine, 'utf8')).toBe('name = "mine"\n');
    expect(fs.readdirSync(at(sb, '.codex/agents'))).toEqual(['mine.toml']);
    for (const root of HARNESS_ROOTS) expect(exists(sb, root)).toBe(true);
  });

  test('sprites: uninstall --dry-run says what it would remove and removes nothing; without bun it keeps the dir and says why', () => {
    const sb = sandbox();
    fullHome(sb);
    expect(sb.run([]).status).toBe(0);
    const before = sb.snapshot();
    const dry = sb.run(['--uninstall', '--dry-run']);
    expect(dry.status).toBe(0);
    for (const id of IDS) {
      expect(dry.stdout).toContain(`[DRY-RUN] Would remove the generated sprite agents from ${at(sb, HARNESS[id].dir)}`);
    }
    expect(sb.snapshot()).toEqual(before);

    fs.rmSync(path.join(sb.bin, 'bun'));
    const r = sb.run(['--uninstall']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain(`[KEEP] ${at(sb, '.codex/agents')} (bun not found; remove the files that carry the line "${MARKER}" by hand)`);
    for (const file of spriteFiles(sb, 'codex')) expect(fs.existsSync(file)).toBe(true);
  });
});

describe('safety and failure', () => {
  test('sprites: a sprite dir that is inside this checkout is skipped by every mode and the checkout stays byte identical', () => {
    const sb = sandbox();
    mkdir(sb, '.claude');
    fs.mkdirSync(path.join(sb.repo, '.claude/agents'), { recursive: true });
    fs.writeFileSync(path.join(sb.repo, '.claude/agents/chef.md'), 'tracked file\n');
    fs.symlinkSync(path.join(sb.repo, '.claude/agents'), at(sb, '.claude/agents'));
    const skip = `[SKIP] claude sprites: ${at(sb, '.claude/agents')} is inside this checkout; left alone`;
    for (const args of [[], ['--update'], ['--check'], ['--uninstall']]) {
      const before = sb.snapshot(sb.repo);
      const r = sb.run(args);
      expect({ args, status: r.status }).toEqual({ args, status: 0 });
      expect(sb.snapshot(sb.repo)).toEqual(before);
      if (args.length === 0) expect(r.stdout).toContain(skip);
    }
    expect(fs.readFileSync(path.join(sb.repo, '.claude/agents/chef.md'), 'utf8')).toBe('tracked file\n');
  });

  test('sprites: a generator that fails does not stop the other harnesses; install places every skill link, then exits 1', () => {
    const sb = sandbox();
    fullHome(sb);
    const realBun = Bun.which('bun');
    fs.rmSync(path.join(sb.bin, 'bun'));
    fs.writeFileSync(
      path.join(sb.bin, 'bun'),
      `#!/bin/sh\ncase "$1" in *gen-sprite-agents.mjs) exit 1 ;; esac\nexec "${realBun}" "$@"\n`,
    );
    fs.chmodSync(path.join(sb.bin, 'bun'), 0o755);
    const r = sb.run([]);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('[FAIL] sprite agents for');
    for (const id of IDS) expect(r.stderr).toContain(`[FAIL] sprite agents for ${id} could not be rendered (see above)`);
    expect(r.stdout).not.toContain('==> Vivera farm planted');
    for (const rel of [
      `.config/ai/${MASTER}`,
      '.agents/skills/super-ultra-code-plan/SKILL.md',
      '.claude/skills/super-ultra-code-plan/SKILL.md',
      '.config/opencode/skills/super-ultra-code-plan/SKILL.md',
      '.gemini/config/skills/super-ultra-code-plan/SKILL.md',
    ]) {
      expect({ rel, link: fs.lstatSync(at(sb, rel), { throwIfNoEntry: false })?.isSymbolicLink() }).toEqual({ rel, link: true });
    }
  });

  test("sprites: a user's hand-written file with a sprite name is refused for that harness only, and left untouched", () => {
    const sb = sandbox();
    mkdir(sb, '.codex/agents');
    const mine = at(sb, '.codex/agents/chef.toml');
    fs.writeFileSync(mine, 'name = "my chef"\n');
    const r = sb.run([]);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('[FAIL] sprite agents for codex could not be rendered (see above)');
    expect(fs.readFileSync(mine, 'utf8')).toBe('name = "my chef"\n');
    const others = sprites(sb).filter((s) => s !== 'chef');
    expect(others.length).toBe(6);
    for (const s of others) expect(isGenerated(at(sb, `.codex/agents/${s}.toml`))).toBe(true);
    expect(backupsUnder(sb)).toEqual([]);
  });
});

// ---- Review round: what --check says about a sprite dir, and a sprite dir that is a symlink ----------

const verdict = (r) => r.stdout.split('\n').filter((l) => l.startsWith('check:'));

describe('check: the state of a sprite dir that exists', () => {
  const dirOf = (sb) => at(sb, '.codex/agents');

  test('sprites: an empty sprite dir is [missing], not [stale]', () => {
    const sb = sandbox();
    mkdir(sb, '.codex/agents');
    const r = sb.run(['--check', '--only', 'codex']);
    expect(r.status).toBe(1);
    expect(r.stdout).toContain(`[missing] ${dirOf(sb)} (sprite agents)`);
    expect(r.stdout).not.toContain('[stale]');
    expect(verdict(r)).toEqual(['check: 1 problem(s)']);
  });

  test('sprites: a sprite dir holding only a hand-written unmarked file is [missing], and the file is untouched', () => {
    const sb = sandbox();
    mkdir(sb, '.codex/agents');
    fs.writeFileSync(at(sb, '.codex/agents/mine.toml'), 'name = "mine"\n');
    const r = sb.run(['--check', '--only', 'codex']);
    expect(r.status).toBe(1);
    expect(r.stdout).toContain(`[missing] ${dirOf(sb)} (sprite agents)`);
    expect(r.stdout).not.toContain('[stale]');
    expect(fs.readFileSync(at(sb, '.codex/agents/mine.toml'), 'utf8')).toBe('name = "mine"\n');
  });

  test('sprites: a partly filled sprite dir (one generated file gone) is [missing]; one gone and another edited is [stale]', () => {
    const sb = sandbox();
    expect(sb.run(['--only', 'codex']).status).toBe(0);
    const [gone, edited] = spriteFiles(sb, 'codex');
    fs.rmSync(gone);
    const partly = sb.run(['--check', '--only', 'codex']);
    expect(partly.status).toBe(1);
    expect(partly.stdout).toContain(`[missing] ${dirOf(sb)} (sprite agents)`);
    expect(partly.stdout).not.toContain('[stale]');

    fs.appendFileSync(edited, '\n# edited by hand\n');
    const mixed = sb.run(['--check', '--only', 'codex']);
    expect(mixed.status).toBe(1);
    expect(mixed.stdout).toContain(`[stale] ${dirOf(sb)} (sprite agents are out of date or hand-edited; --update renders them again)`);
    expect(mixed.stdout).not.toContain('[missing]');
  });
});

describe('check: a generator that fails is [FAIL] with its own message, never the --update advice', () => {
  const failLine = (r) => r.stdout.split('\n').find((l) => l.startsWith('[FAIL] codex sprites: '));

  test('sprites: a hand-written file with a sprite name gives the generator refusal line and exit 1', () => {
    const sb = sandbox();
    mkdir(sb, '.codex/agents');
    const mine = at(sb, '.codex/agents/chef.toml');
    fs.writeFileSync(mine, 'name = "my chef"\n');
    const r = sb.run(['--check', '--only', 'codex']);
    expect(r.status).toBe(1);
    expect(failLine(r)).toBe(`[FAIL] codex sprites: ${mine}: not generated by this script, left untouched`);
    expect(r.stdout).not.toContain('--update renders them again');
    expect(r.stdout).not.toContain('[stale]');
    expect(r.stdout).not.toContain('[missing]');
    expect(verdict(r)).toEqual(['check: 1 problem(s)']);
    expect(fs.readFileSync(mine, 'utf8')).toBe('name = "my chef"\n');
  });

  test('sprites: a corrupt agents/crew.json and a missing generator each give a [FAIL] line with a message', () => {
    for (const break_ of [
      (sb) => fs.writeFileSync(path.join(sb.repo, 'agents/crew.json'), '{not json'),
      (sb) => fs.rmSync(path.join(sb.repo, 'scripts/gen-sprite-agents.mjs')),
    ]) {
      const sb = sandbox();
      mkdir(sb, '.codex/agents');
      break_(sb);
      const r = sb.run(['--check', '--only', 'codex']);
      expect(r.status).toBe(1);
      expect((failLine(r) ?? '').length).toBeGreaterThan('[FAIL] codex sprites: '.length);
      expect(r.stdout).not.toContain('--update renders them again');
      expect(r.stdout).not.toContain('[stale]');
      expect(verdict(r)).toEqual(['check: 1 problem(s)']);
    }
  });

  test('sprites: real drift still says [stale] with the --update advice (control)', () => {
    const sb = sandbox();
    expect(sb.run(['--only', 'codex']).status).toBe(0);
    fs.appendFileSync(spriteFiles(sb, 'codex')[0], '\n# edited by hand\n');
    const r = sb.run(['--check', '--only', 'codex']);
    expect(r.status).toBe(1);
    expect(r.stdout).toContain('--update renders them again');
    expect(r.stdout).not.toContain('[FAIL]');
  });
});

describe('check: a skipped sprite check is never reported as plain CURRENT', () => {
  test('sprites: nothing checked and the sprite checks skipped says what was skipped and why, still exit 2', () => {
    const noBun = sandbox({ tools: [] }).run(['--check', '--only', 'codex']);
    expect(noBun.status).toBe(2);
    expect(verdict(noBun)).toEqual([
      'check: nothing to check (no selected target has skills); sprite agents not verified: bun is missing',
    ]);

    const minimal = sandbox({ tools: [] }).run(['--check', '--only', 'codex', '--tier', 'minimal']);
    expect(minimal.status).toBe(2);
    expect(verdict(minimal)).toEqual([
      'check: nothing to check (no selected target has skills); sprite agents not verified: tier minimal renders none',
    ]);
  });

  test('sprites: skills current but no bun ends with CURRENT plus the unverified note, exit 0; with bun it is plain CURRENT', () => {
    const sb = sandbox();
    fullHome(sb);
    expect(sb.run([]).status).toBe(0);
    expect(verdict(sb.run(['--check']))).toEqual(['check: CURRENT']);

    fs.rmSync(path.join(sb.bin, 'bun'));
    for (const args of [['--check'], ['--check', '--only', 'claude,codex']]) {
      const r = sb.run(args);
      expect({ args, status: r.status }).toEqual({ args, status: 0 });
      expect(verdict(r)).toEqual(['check: CURRENT (sprite agents not verified: bun is missing)']);
    }
  });

  test('sprites: tier minimal with skills current ends with the unverified note too', () => {
    const sb = sandbox({ tools: [] });
    fullHome(sb);
    expect(sb.run(['--tier', 'minimal']).status).toBe(0);
    const r = sb.run(['--check', '--tier', 'minimal']);
    expect(r.status).toBe(0);
    expect(verdict(r)).toEqual(['check: CURRENT (sprite agents not verified: tier minimal renders none)']);
  });
});

describe('a sprite dir reached through a symlinked directory is left alone, like skills', () => {
  const via = (sb, rel) => `${at(sb, rel)} is reached through a symlinked directory; left alone`;

  // The real files live in a dotfiles dir outside HOME; HOME holds a symlink to it.
  function dotfilesAgents(sb) {
    expect(sb.run(['--only', 'codex']).status).toBe(0);
    const dot = path.join(sb.root, 'dotfiles-agents');
    fs.renameSync(at(sb, '.codex/agents'), dot);
    fs.symlinkSync(dot, at(sb, '.codex/agents'));
    fs.appendFileSync(path.join(dot, fs.readdirSync(dot)[0]), '\n# edited in the dotfiles repo\n');
    return dot;
  }

  test('sprites: install and update write nothing through it and say so, the last line counts it', () => {
    for (const args of [['--only', 'codex'], ['--update', '--only', 'codex']]) {
      const sb = sandbox();
      const dot = dotfilesAgents(sb);
      const before = sb.snapshot(dot);
      const r = sb.run(args);
      expect({ args, status: r.status }).toEqual({ args, status: 0 });
      expect(r.stdout).toContain(`[SKIP] codex sprites: ${via(sb, '.codex/agents')}`);
      expect(r.stdout).toContain('==> Vivera finished with 1 entry left alone (see the [SKIP] lines above)');
      expect(sb.snapshot(dot)).toEqual(before);
    }
  });

  test('sprites: --check prints a [skip] line, no [stale], no problem, and does not claim CURRENT without the note', () => {
    const sb = sandbox();
    expect(sb.run(['--only', 'agents,codex']).status).toBe(0);
    const dot = dotfilesAgents(sb);
    const before = sb.snapshot(dot);
    const r = sb.run(['--check', '--only', 'agents,codex']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain(`[skip] codex sprites: ${via(sb, '.codex/agents')}`);
    expect(r.stdout).not.toContain('[stale]');
    expect(verdict(r)).toEqual(['check: CURRENT (sprite agents not verified: a sprite dir is reached through a symlinked directory)']);
    expect(sb.snapshot(dot)).toEqual(before);
  });

  test('sprites: uninstall removes nothing through it and says so', () => {
    const sb = sandbox();
    const dot = dotfilesAgents(sb);
    const before = sb.snapshot(dot);
    const r = sb.run(['--uninstall', '--only', 'codex']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain(`[SKIP] codex sprites: ${via(sb, '.codex/agents')}`);
    expect(sb.snapshot(dot)).toEqual(before);
    expect(fs.lstatSync(at(sb, '.codex/agents')).isSymbolicLink()).toBe(true);
  });

  test('sprites: a harness root that is a symlink with no agents dir yet gets none created in the other tree', () => {
    const sb = sandbox();
    const dot = path.join(sb.root, 'dotfiles-codex');
    fs.mkdirSync(dot);
    fs.symlinkSync(dot, at(sb, '.codex'));
    const r = sb.run(['--only', 'codex']);
    expect(r.status).toBe(0);
    expect(r.stdout).toContain(`[SKIP] codex sprites: ${via(sb, '.codex/agents')}`);
    expect(fs.readdirSync(dot)).toEqual([]);
  });
});
