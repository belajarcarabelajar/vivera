#!/usr/bin/env bun
// scripts/gen-sprite-agents.mjs
//
// Renders the Harvest Sprite crew into Claude Code subagent files. Claude Code
// labels a running subagent with its agent name, so four role agents shared by
// a wave of parallel chunks all show the same label. Each sprite is a named copy
// of one role template (agents/roles/<role>.md), listed in agents/crew.json.
//
// Targets:
//   - the repository's .claude/agents (default), committed and checked in CI;
//   - a user-level directory such as ~/.claude/agents (install.sh), where
//     $CLAUDE_PROJECT_DIR points at whatever project the session opened, so the
//     hook path is pinned to this repository with --hook-root. Without that the
//     guard script is missing in other projects and the hook stops guarding;
//   - --target opencode with --out ~/.config/opencode/agents (install.sh): the
//     OpenCode v2 format, which skips a Claude Code file without a message.
//
// Usage: bun scripts/gen-sprite-agents.mjs [--check] [--out <dir>] [--hook-root <dir>]
//                                          [--target claude|opencode] [--roles <dir>] [--crew <file>]
// Exit: 0 in sync or written, 1 drift, refusal, or bad input.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENUMS } from './validate-agents.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const MARKER = '# Generated by scripts/gen-sprite-agents.mjs';

const SPRITE_NAME = /^[a-z][a-z0-9-]*$/;
const PROJECT_DIR = /\$(?:\{CLAUDE_PROJECT_DIR\}|CLAUDE_PROJECT_DIR\b)/g;

function splitFrontmatter(text, label) {
  const lines = text.split('\n');
  const end = lines.indexOf('---', 1);
  if (lines[0] !== '---' || end === -1) throw new Error(`${label}: no frontmatter between two "---" lines`);
  return { head: lines.slice(1, end), body: lines.slice(end + 1).join('\n') };
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function checkHookRoot(hookRoot) {
  // The root lands inside a double-quoted YAML string that the hook runner hands
  // to a shell, so a quote, a backslash, or an expansion character would change
  // the command instead of naming a directory.
  if (!path.isAbsolute(hookRoot) || /["\\$`\n]/.test(hookRoot)) {
    throw new Error(`hook root must be an absolute path without quotes, backslashes, "$", backticks, or newlines (got ${JSON.stringify(hookRoot)})`);
  }
}

export function renderAgent(template, member, { hookRoot, templateLabel = `agents/roles/${member.role}.md` } = {}) {
  if (hookRoot !== undefined) checkHookRoot(hookRoot);
  const { head, body } = splitFrontmatter(template, templateLabel);
  const fm = Bun.YAML.parse(head.join('\n')) ?? {};
  for (const key of ['name', 'color']) {
    if (key in fm) throw new Error(`${templateLabel}: a role template must not set "${key}"; the crew roster sets it per sprite`);
  }
  if (typeof fm.description !== 'string' || fm.description.trim() === '') {
    throw new Error(`${templateLabel}: "description" is required`);
  }
  const descLine = head.findIndex((l) => l.startsWith('description:'));
  if (descLine === -1 || /^description:\s*[|>]/.test(head[descLine])) {
    throw new Error(`${templateLabel}: "description" must be a single line`);
  }

  const description = `${capitalize(member.sprite)}, a Harvest Sprite on the ${member.role} crew. ${fm.description.trim()}`;
  const rest = head.filter((_, i) => i !== descLine).map((l) => (hookRoot === undefined ? l : l.replace(PROJECT_DIR, hookRoot)));
  return [
    '---',
    `name: ${member.sprite}`,
    `description: ${JSON.stringify(description)}`,
    `color: ${member.color}`,
    ...rest,
    `${MARKER} from ${templateLabel} and agents/crew.json; edit those, then run bun run agents:gen.`,
    '---',
    body,
  ].join('\n');
}

// OpenCode v2 takes a six-digit hex color and skips the whole agent, without a
// message, when it gets a color name (measured on v2.0.24).
export const OPENCODE_COLORS = {
  red: '#e5484d',
  orange: '#f76b15',
  yellow: '#ffc53d',
  green: '#46a758',
  blue: '#0090ff',
  purple: '#8e4ec6',
  pink: '#d6409f',
  cyan: '#00a2c7',
};

const GUARD_SCRIPT = 'block-git-writes.mjs';
const OPENCODE_TEMPLATE_KEYS = ['description', 'tools', 'skills', 'maxTurns', 'hooks'];

// OpenCode has no hooks, so the git guard becomes shell permission rules. The
// last matching rule wins and each command of a chain is matched on its own
// (both measured on v2.0.24). The rtk plugin rewrites `git x` to `rtk git x`
// before the match, so every rule also has an rtk form. Matching arguments the
// way the hook does would take hundreds of globs, so this is an allowlist: all
// of git and gh is denied, then common read-only forms are allowed again. An
// allowed pattern only ends in a wildcard, because a wildcard in the middle
// (`git -C * diff*`) also matches `git -C x commit -m "fix diff"`.
const GIT_READS = [
  'status', 'diff', 'log', 'show', 'blame', 'grep', 'rev-parse', 'rev-list', 'ls-files', 'ls-tree',
  'cat-file', 'describe', 'shortlog', 'merge-base', 'name-rev', 'for-each-ref', 'show-ref',
  'count-objects', 'reflog show', 'stash list', 'stash show', 'worktree list', 'remote -v',
  'remote get-url', 'branch --show-current', 'branch --list', 'tag --list', 'config --get', 'config --list',
];
const GIT_BARE_READS = ['branch', 'tag', 'reflog', 'remote', 'version', '--version'];

function openCodeShellRules() {
  const deny = ['git *', 'rtk git *', 'gh', 'gh *', 'rtk gh *', '*/git *', '*/gh *'];
  const allow = [];
  for (const prefix of ['git', 'rtk git']) {
    for (const sub of GIT_READS) allow.push(`${prefix} ${sub}*`);
    for (const sub of GIT_BARE_READS) allow.push(`${prefix} ${sub}`);
  }
  return [
    ...deny.map((resource) => ({ action: 'shell', resource, effect: 'deny' })),
    ...allow.map((resource) => ({ action: 'shell', resource, effect: 'allow' })),
  ];
}

export function renderOpenCodeAgent(template, member, { templateLabel = `agents/roles/${member.role}.md` } = {}) {
  const { head, body } = splitFrontmatter(template, templateLabel);
  const fm = Bun.YAML.parse(head.join('\n')) ?? {};
  for (const key of Object.keys(fm)) {
    if (!OPENCODE_TEMPLATE_KEYS.includes(key)) {
      throw new Error(`${templateLabel}: "${key}" has no OpenCode translation in gen-sprite-agents.mjs; add one before using it`);
    }
  }
  if (typeof fm.description !== 'string' || fm.description.trim() === '') {
    throw new Error(`${templateLabel}: "description" is required`);
  }
  for (const entries of Object.values(fm.hooks ?? {})) {
    for (const hook of entries.flatMap((e) => e.hooks ?? [])) {
      if (!String(hook.command ?? '').includes(GUARD_SCRIPT)) {
        throw new Error(`${templateLabel}: OpenCode has no hooks and only the git guard has a permission translation, not ${hook.command}`);
      }
    }
  }

  const permissions = fm.hooks ? openCodeShellRules() : [];
  const tools = typeof fm.tools === 'string' ? fm.tools.split(',').map((t) => t.trim()) : fm.tools;
  if (Array.isArray(tools) && !tools.some((t) => ['Edit', 'Write', 'MultiEdit', 'NotebookEdit'].includes(t))) {
    permissions.push({ action: 'edit', resource: '*', effect: 'deny' });
  }

  const description = `${capitalize(member.sprite)}, a Harvest Sprite on the ${member.role} crew. ${fm.description.trim()}`;
  const lines = ['---', `description: ${JSON.stringify(description)}`, 'mode: subagent', `color: "${OPENCODE_COLORS[member.color]}"`];
  if (Number.isInteger(fm.maxTurns)) lines.push(`steps: ${fm.maxTurns}`);
  if (permissions.length > 0) {
    lines.push('permissions:');
    for (const p of permissions) lines.push(`  - { action: ${p.action}, resource: ${JSON.stringify(p.resource)}, effect: ${p.effect} }`);
  }
  lines.push(`${MARKER} from ${templateLabel} and agents/crew.json; edit those, then run ./install.sh.`, '---');

  const preface = [];
  if (Array.isArray(fm.skills) && fm.skills.length > 0) {
    const names = fm.skills.map((s) => `\`${s}\``).join(', ');
    preface.push('', `Load the ${names} skill with the skill tool before anything else; it holds the rules of your phase.`);
  }
  if (fm.hooks) {
    preface.push('', 'In this harness the guard allows only common read-only git forms and blocks `git -C`; run `cd <dir> && git <command>` instead.');
  }
  return [...lines, ...preface, body].join('\n');
}

export function parseCrew(json) {
  const crew = JSON.parse(json);
  if (!Array.isArray(crew)) throw new Error('crew must be a JSON array');
  if (crew.length === 0) throw new Error('crew must not be empty');
  const seen = new Set();
  crew.forEach((m, i) => {
    const at = `crew[${i}]`;
    if (typeof m?.sprite !== 'string' || !SPRITE_NAME.test(m.sprite)) {
      throw new Error(`${at}: "sprite" must be lowercase letters, digits, and hyphens`);
    }
    if (seen.has(m.sprite)) throw new Error(`${at}: duplicate sprite "${m.sprite}"`);
    seen.add(m.sprite);
    if (typeof m.role !== 'string' || !SPRITE_NAME.test(m.role)) throw new Error(`${at}: "role" must name a template in agents/roles`);
    if (!ENUMS.color.includes(m.color)) throw new Error(`${at}: "color" must be one of ${ENUMS.color.join(', ')}`);
  });
  return crew;
}

// Repository-relative paths that the templates' hooks run under $CLAUDE_PROJECT_DIR.
function hookScripts(template) {
  const found = new Set();
  for (const m of template.matchAll(/\$(?:\{CLAUDE_PROJECT_DIR\}|CLAUDE_PROJECT_DIR\b)(?:\\?")?(\/[^\s"\\]+)/g)) found.add(m[1]);
  return [...found];
}

export function planOutputs({ rolesDir, crewFile, hookRoot, target = 'claude' }) {
  const crew = parseCrew(fs.readFileSync(crewFile, 'utf8'));
  const roles = fs
    .readdirSync(rolesDir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => f.slice(0, -3));
  for (const m of crew) {
    if (!roles.includes(m.role)) throw new Error(`crew: sprite "${m.sprite}" names role "${m.role}", which has no ${path.join(rolesDir, `${m.role}.md`)}`);
  }
  const idle = roles.filter((r) => !crew.some((m) => m.role === r));
  if (idle.length > 0) throw new Error(`crew: no sprite is assigned to role(s) ${idle.join(', ')}`);

  const outputs = new Map();
  for (const m of crew) {
    const template = fs.readFileSync(path.join(rolesDir, `${m.role}.md`), 'utf8');
    if (hookRoot !== undefined) {
      for (const rel of hookScripts(template)) {
        if (!fs.existsSync(path.join(hookRoot, rel))) throw new Error(`hook script ${path.join(hookRoot, rel)} does not exist`);
      }
    }
    outputs.set(`${m.sprite}.md`, target === 'opencode' ? renderOpenCodeAgent(template, m) : renderAgent(template, m, { hookRoot }));
  }
  return outputs;
}

function isGenerated(file) {
  try {
    return fs.readFileSync(file, 'utf8').split('\n').some((l) => l.startsWith(MARKER));
  } catch {
    return false;
  }
}

export function syncDir(outDir, outputs, { check = false } = {}) {
  const result = { written: [], removed: [], refused: [], drift: [] };
  const existing = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((f) => f.endsWith('.md')) : [];

  for (const [file, content] of outputs) {
    const full = path.join(outDir, file);
    if (!existing.includes(file)) {
      if (check) result.drift.push(`${file}: missing`);
      else {
        fs.mkdirSync(outDir, { recursive: true });
        fs.writeFileSync(full, content);
        result.written.push(file);
      }
    } else if (fs.readFileSync(full, 'utf8') !== content) {
      // A same-named file without the marker belongs to someone else.
      if (!isGenerated(full)) result.refused.push(file);
      else if (check) result.drift.push(`${file}: out of date`);
      else {
        fs.writeFileSync(full, content);
        result.written.push(file);
      }
    }
  }

  for (const file of existing) {
    if (outputs.has(file) || !isGenerated(path.join(outDir, file))) continue;
    if (check) result.drift.push(`${file}: stale, its sprite left the crew`);
    else {
      fs.rmSync(path.join(outDir, file));
      result.removed.push(file);
    }
  }
  return result;
}

function parseArgs(argv) {
  const opts = {
    check: false,
    rolesDir: path.join(ROOT, 'agents', 'roles'),
    crewFile: path.join(ROOT, 'agents', 'crew.json'),
    outDir: undefined,
    hookRoot: undefined,
    target: 'claude',
  };
  const valued = { '--roles': 'rolesDir', '--crew': 'crewFile', '--out': 'outDir', '--hook-root': 'hookRoot' };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--target' && i + 1 < argv.length) opts.target = argv[++i];
    else if (arg in valued && i + 1 < argv.length) opts[valued[arg]] = path.resolve(argv[++i]);
    else throw new Error(`unknown or incomplete argument: ${arg}`);
  }
  if (!['claude', 'opencode'].includes(opts.target)) throw new Error(`--target must be claude or opencode (got ${opts.target})`);
  if (opts.target === 'opencode') {
    // Nothing of OpenCode's is committed here, so there is no safe default directory.
    if (opts.outDir === undefined) throw new Error('--target opencode needs --out, for example ~/.config/opencode/agents');
    if (opts.hookRoot !== undefined) throw new Error('--hook-root applies to Claude Code hooks only; OpenCode gets permission rules');
  }
  opts.outDir ??= path.join(ROOT, '.claude', 'agents');
  return opts;
}

if (import.meta.main) {
  try {
    const opts = parseArgs(process.argv.slice(2));
    const outputs = planOutputs(opts);
    const r = syncDir(opts.outDir, outputs, { check: opts.check });
    for (const f of r.refused) console.error(`${path.join(opts.outDir, f)}: not generated by this script, left untouched`);
    for (const d of r.drift) console.error(`${path.join(opts.outDir, d)}`);
    if (r.drift.length > 0) console.error('sprite agents are out of date: run bun run agents:gen');
    if (r.refused.length > 0 || r.drift.length > 0) process.exit(1);
    const changes = opts.check ? 'in sync' : `${r.written.length} written, ${r.removed.length} removed`;
    console.log(`${outputs.size} sprite agent(s) in ${opts.outDir}: ${changes}`);
  } catch (e) {
    console.error(String(e.message));
    process.exit(1);
  }
}
