// scripts/install-baseline.test.mjs
//
// Characterization tests: they pin what install.sh does TODAY, so a later task
// that changes the installer shows up as a test diff instead of a surprise.
// Every run uses a temp HOME and a copy of the installer payload (see
// scripts/lib/install-sandbox.mjs); the real HOME and the real repo are never
// written.

import { afterEach, expect, test } from 'bun:test';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertSandbox, INSTALL_PAYLOAD, makeSandbox } from './lib/install-sandbox.mjs';

const WORKTREE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MASTER = 'Super Ultra Code Plan Implementation.md';
const MARKER = '# Generated by scripts/gen-sprite-agents.mjs';
const BUILTIN = '.gemini/antigravity-cli/builtin/skills';
const REPO_REF = '<ROOT>/repo';

const open = [];
afterEach(() => {
  while (open.length) open.pop().cleanup();
});

function sandbox(opts) {
  const sb = makeSandbox(opts);
  open.push(sb);
  return sb;
}

const mkdirHome = (sb, rel) => fs.mkdirSync(path.join(sb.home, rel), { recursive: true });
const readCrew = (sb) => JSON.parse(fs.readFileSync(path.join(sb.repo, 'agents', 'crew.json'), 'utf8'));
const sprites = (sb) => readCrew(sb).map((c) => c.sprite);
const phaseSkills = (sb) => fs.readdirSync(path.join(sb.repo, 'skills')).filter((n) => n.startsWith('sucp-')).sort();

// The link set install.sh must create, as snapshot-style entries. File content
// is checked apart (a hash would pin the generator, not the installer), so a
// file entry carries an empty detail on both sides of the comparison. Since T06 a bare home gets
// only ai-config and agents; every other harness needs its detection fixture (the options below).
// `builtin` stands for the Antigravity fixture dir, which also makes ~/.gemini and the CLI dir exist.
function expectedLayout(sb, { opencode = false, claude = false, builtin = false } = {}) {
  const want = new Map();
  const add = (rel, type, detail = '') => {
    want.set(rel, `${type}|${detail}`);
    for (let dir = path.posix.dirname(rel); dir !== '.'; dir = path.posix.dirname(dir)) want.set(dir, 'd|');
  };
  add(`.config/ai/${MASTER}`, 'l', `${REPO_REF}/${MASTER}`);
  const roots = ['.agents/skills'];
  if (builtin) roots.push('.gemini/config/skills', '.gemini/antigravity-cli/skills', BUILTIN);
  if (opencode) roots.push('.config/opencode/skills');
  if (claude) roots.push('.claude/skills');
  for (const root of roots) {
    const pkg = `${root}/super-ultra-code-plan`;
    add(pkg, 'd');
    add(`${pkg}/SKILL.md`, 'l', `${REPO_REF}/${MASTER}`);
    add(`${pkg}/templates`, 'l', `${REPO_REF}/templates`);
    add(`${pkg}/examples`, 'l', `${REPO_REF}/examples`);
    add(`${pkg}/mermaid.config.json`, 'l', `${REPO_REF}/mermaid.config.json`);
    add(`${pkg}/mermaid.dark.config.json`, 'l', `${REPO_REF}/mermaid.dark.config.json`);
    for (const name of phaseSkills(sb)) {
      add(`${root}/${name}`, 'd');
      add(`${root}/${name}/SKILL.md`, 'l', `${REPO_REF}/skills/${name}/SKILL.md`);
    }
  }
  for (const s of sprites(sb)) {
    if (opencode) add(`.config/opencode/agents/${s}.md`, 'f');
    // T17: the Antigravity target also renders its sprite agents, one dir per sprite.
    if (builtin) add(`.gemini/config/agents/${s}/agent.md`, 'f');
    if (claude) add(`.claude/agents/${s}.md`, 'f');
  }
  return want;
}

function snapshotLines(sb) {
  return sb
    .snapshot()
    .map((line) => {
      const [rel, type, ...rest] = line.split('|');
      return `${rel}|${type}|${type === 'f' ? '' : rest.join('|')}`;
    })
    .sort();
}

function expectLayout(sb, opts) {
  const want = [...expectedLayout(sb, opts)].map(([rel, v]) => `${rel}|${v}`).sort();
  expect(snapshotLines(sb)).toEqual(want);
}

function expectGeneratedSprites(sb, dir) {
  const names = sprites(sb);
  expect(names.length).toBeGreaterThan(0);
  for (const s of names) {
    const file = path.join(sb.home, dir, `${s}.md`);
    // The generator's own ownership test is startsWith: the line goes on with the source and revert text.
    expect(fs.readFileSync(file, 'utf8').split('\n').some((l) => l.startsWith(MARKER))).toBe(true);
  }
}

test('baseline: --dry-run prints DRY-RUN lines and leaves the home untouched', () => {
  const sb = sandbox({ tools: ['git', 'bun'] });
  mkdirHome(sb, '.claude');
  mkdirHome(sb, BUILTIN);
  fs.writeFileSync(path.join(sb.home, 'keep.txt'), 'x');
  const before = sb.snapshot();
  expect(before.length).toBeGreaterThan(0);
  const r = sb.run(['--dry-run']);
  expect(r.status).toBe(0);
  expect(r.stdout).toContain('[DRY-RUN]');
  expect(sb.snapshot()).toEqual(before);
});

test('baseline: a real run on a bare home creates only ai-config and agents (changed in T06, OpenCode and Gemini were unconditional)', () => {
  const sb = sandbox({ tools: ['git', 'bun'] });
  expect(phaseSkills(sb).length).toBeGreaterThan(0);
  const r = sb.run([]);
  expect(r.status).toBe(0);
  expectLayout(sb);
  for (const absent of ['.claude', '.gemini', '.config/opencode']) {
    expect(fs.existsSync(path.join(sb.home, absent))).toBe(false);
  }
});

test('baseline: with ~/.config/opencode present the run installs the OpenCode package and sprites (changed in T06, it was unconditional)', () => {
  const sb = sandbox({ tools: ['git', 'bun'] });
  mkdirHome(sb, '.config/opencode');
  const r = sb.run([]);
  expect(r.status).toBe(0);
  expectLayout(sb, { opencode: true });
  expectGeneratedSprites(sb, '.config/opencode/agents');
});

test('baseline: with ~/.claude present the run also installs the Claude Code package and sprites (changed in T06, no OpenCode or Gemini links)', () => {
  const sb = sandbox({ tools: ['git', 'bun'] });
  mkdirHome(sb, '.claude');
  const r = sb.run([]);
  expect(r.status).toBe(0);
  expectLayout(sb, { claude: true });
  expect(fs.lstatSync(path.join(sb.home, '.claude/skills/super-ultra-code-plan/SKILL.md')).isSymbolicLink()).toBe(true);
  expectGeneratedSprites(sb, '.claude/agents');
});

test('baseline: with the Antigravity builtin skills dir present the run also installs Antigravity and its CLI (changed in T06)', () => {
  const sb = sandbox({ tools: ['git', 'bun'] });
  mkdirHome(sb, BUILTIN);
  const r = sb.run([]);
  expect(r.status).toBe(0);
  expectLayout(sb, { builtin: true });
  expect(fs.lstatSync(path.join(sb.home, BUILTIN, 'super-ultra-code-plan/SKILL.md')).isSymbolicLink()).toBe(true);
});

test('baseline: a second real run leaves the home byte identical', () => {
  const sb = sandbox({ tools: ['git', 'bun'] });
  mkdirHome(sb, '.claude');
  mkdirHome(sb, BUILTIN);
  expect(sb.run([]).status).toBe(0);
  const first = sb.snapshot();
  expect(first.length).toBeGreaterThan(0);
  expect(sb.run([]).status).toBe(0);
  expect(sb.snapshot()).toEqual(first);
});

