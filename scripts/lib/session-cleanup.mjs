// scripts/lib/session-cleanup.mjs
//
// Removes the worktree a finished session leaves behind. `git worktree remove`
// refuses uncommitted work but deletes gitignored files without a word, and in
// a session worktree those can be generated voiceovers, data, or plans under
// docs/code-plan/. So ignored files are sorted first: build output and caches go,
// files identical to the main checkout go, unique files are copied to the same
// path in the main checkout (never over an existing file), and anything that
// would need an overwrite keeps the whole worktree.

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

// Regenerated by the next install or build; never worth keeping.
const DISPOSABLE = new Set([
  'node_modules', 'dist', 'build', 'target', '.turbo', '.cache', '__pycache__', '.pytest_cache',
  '.mypy_cache', '.ruff_cache', '.wrangler', '.astro', '.next', '.svelte-kit', 'coverage', '.venv',
  '.mermaid-tmp', '.DS_Store',
]);
const DISPOSABLE_EXT = ['.pyc', '.tsbuildinfo'];

function git(cwd, args) {
  const r = spawnSync('git', ['-C', cwd, ...args], { encoding: 'utf8' });
  return { code: r.status, out: (r.stdout ?? '').trim(), err: (r.stderr ?? '').trim() };
}

function gitOk(cwd, args) {
  const r = git(cwd, args);
  if (r.code !== 0) throw new Error(`git ${args.join(' ')}: ${r.err}`);
  return r.out;
}

export function listProcCwds() {
  const out = [];
  for (const pid of fs.readdirSync('/proc').filter((n) => /^\d+$/.test(n))) {
    try {
      out.push({ pid: Number(pid), cwd: fs.readlinkSync(`/proc/${pid}/cwd`) });
    } catch {
      // The process exited or belongs to another user.
    }
  }
  return out;
}

const inside = (p, root) => p === root || p.startsWith(root + path.sep);
const exists = (p) => { try { fs.lstatSync(p); return true; } catch { return false; } };
const disposable = (rel) => rel.split('/').some((seg) => DISPOSABLE.has(seg)) || DISPOSABLE_EXT.some((ext) => rel.endsWith(ext));

// Files and symlinks under rel, without following links. A disposable path found
// on the way, such as node_modules inside an ignored data directory, goes to dropped.
function filesUnder(root, rel, dropped) {
  const st = fs.lstatSync(path.join(root, rel));
  if (disposable(rel)) {
    dropped.push(st.isDirectory() ? `${rel}/` : rel);
    return [];
  }
  if (!st.isDirectory()) return [rel];
  return fs.readdirSync(path.join(root, rel)).sort().flatMap((name) => filesUnder(root, path.posix.join(rel, name), dropped));
}

function sameEntry(a, b) {
  const sa = fs.lstatSync(a);
  const sb = fs.lstatSync(b);
  if (sa.isSymbolicLink() || sb.isSymbolicLink()) return sa.isSymbolicLink() && sb.isSymbolicLink() && fs.readlinkSync(a) === fs.readlinkSync(b);
  return sa.isFile() && sb.isFile() && sa.size === sb.size && fs.readFileSync(a).equals(fs.readFileSync(b));
}

// A link into the main checkout (a shared .env, say) points at data that outlives the worktree.
function linksInto(file, root) {
  if (!fs.lstatSync(file).isSymbolicLink()) return false;
  try {
    return inside(fs.realpathSync(file), root);
  } catch {
    return false;
  }
}

export function planCleanup({ worktree, procCwds = listProcCwds() }) {
  const wt = fs.realpathSync(worktree);
  if (fs.realpathSync(gitOk(wt, ['rev-parse', '--show-toplevel'])) !== wt) throw new Error(`${worktree} is not the top of a git worktree`);
  const main = fs.realpathSync(gitOk(wt, ['worktree', 'list', '--porcelain']).split('\n')[0].replace(/^worktree /, ''));
  if (main === wt) throw new Error(`${worktree} is the main checkout, which is never removed`);
  const head = gitOk(wt, ['rev-parse', '--abbrev-ref', 'HEAD']);
  const plan = { worktree: wt, main, branch: head === 'HEAD' ? null : head, blockers: [], disposable: [], identical: [], salvage: [], conflicts: [] };

  for (const { pid, cwd } of procCwds) {
    if (pid !== process.pid && inside(cwd, wt)) plan.blockers.push(`process ${pid} works inside the worktree (cwd ${cwd})`);
  }
  const entries = git(wt, ['status', '--porcelain=v1', '--ignored', '-z']).out.split('\0').filter(Boolean);
  for (const e of entries) {
    const rel = e.slice(3);
    if (!e.startsWith('!! ')) {
      plan.blockers.push(`uncommitted change: ${e}`);
      continue;
    }
    if (disposable(rel)) {
      plan.disposable.push(rel);
      continue;
    }
    for (const file of filesUnder(wt, rel.replace(/\/$/, ''), plan.disposable)) {
      const target = path.join(main, file);
      if (linksInto(path.join(wt, file), main)) plan.identical.push(file);
      else if (!exists(target)) plan.salvage.push(file);
      else if (sameEntry(path.join(wt, file), target)) plan.identical.push(file);
      else plan.conflicts.push(file);
    }
  }
  for (const file of plan.conflicts) plan.blockers.push(`ignored file differs from the main checkout: ${file}`);
  return plan;
}

function copyEntry(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  if (fs.lstatSync(from).isSymbolicLink()) fs.symlinkSync(fs.readlinkSync(from), to);
  else fs.copyFileSync(from, to, fs.constants.COPYFILE_EXCL);
  if (!sameEntry(from, to)) throw new Error(`copy of ${from} to ${to} does not match`);
}

function branchMerged(main, branch, base) {
  git(main, ['fetch', '-q', 'origin', base]);
  return git(main, ['merge-base', '--is-ancestor', branch, `origin/${base}`]).code === 0;
}

// status: removed, kept (a blocker holds the worktree), or dry-run.
export function runCleanup({ worktree, base = 'main', dryRun = false, procCwds }) {
  const p = planCleanup({ worktree, procCwds });
  if (p.blockers.length) return { status: 'kept', lines: [`kept ${p.worktree}:`, ...p.blockers.map((b) => `  - ${b}`)] };
  const summary = [
    ...p.salvage.map((f) => `  salvage to the main checkout: ${f}`),
    ...p.identical.map((f) => `  identical in the main checkout: ${f}`),
    ...p.disposable.map((f) => `  disposable: ${f}`),
  ];
  if (dryRun) {
    const merged = p.branch && branchMerged(p.main, p.branch, base);
    const branchLine = p.branch ? `  branch ${p.branch} ${merged ? 'would be deleted' : 'would be kept'} (${merged ? 'in' : 'not in'} origin/${base})` : '  detached HEAD, no branch';
    return { status: 'dry-run', lines: [`would remove ${p.worktree}`, ...summary, branchLine] };
  }
  for (const f of p.salvage) copyEntry(path.join(p.worktree, f), path.join(p.main, f));
  gitOk(p.main, ['worktree', 'remove', p.worktree]);
  gitOk(p.main, ['worktree', 'prune']);
  const lines = [`removed ${p.worktree}`, ...summary];
  if (!p.branch) lines.push('  detached HEAD, no branch');
  else if (!branchMerged(p.main, p.branch, base)) lines.push(`  branch ${p.branch} kept: not in origin/${base}`);
  else {
    const r = git(p.main, ['branch', '-d', p.branch]);
    lines.push(r.code === 0 ? `  branch ${p.branch} deleted (in origin/${base})` : `  branch ${p.branch} kept: git branch -d refused (${r.err})`);
  }
  return { status: 'removed', lines };
}
